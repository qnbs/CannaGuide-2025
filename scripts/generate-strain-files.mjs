const HEADER = `// AUTO-GENERATED by scripts/generate-strain-files.mjs
// Do not edit manually. Edit strains.json and run: pnpm run strains:generate
import { type Strain, StrainType } from '@/types'
import { createStrainObject } from '@/services/strainFactory'`

/** Escape a string for embedding in a single-quoted JS literal. */
const escapeStr = (s) =>
    String(s)
        .replace(/\\/g, '\\\\')
        .replace(/'/g, "\\'")
        .replace(/[\u0000-\u001F\u2028\u2029]/g, (ch) => {
            if (ch === '\n') return '\\n'
            if (ch === '\r') return '\\r'
            if (ch === '\t') return '\\t'
            return `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`
        })

const TYPE_ENUM = Object.assign(Object.create(null), {
    Sativa: 'StrainType.Sativa',
    Indica: 'StrainType.Indica',
    Hybrid: 'StrainType.Hybrid',
})

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/
const SAFE_KEY = /^[A-Za-z0-9_$. -]+$/
const QUOTED_IDENTIFIER = new Set(['__proto__', 'constructor', 'prototype'])

const isBareIdentifier = (text) =>
    SAFE_KEY.test(text) && IDENTIFIER.test(text) && !QUOTED_IDENTIFIER.has(text)

const emitKey = (key) => {
    const text = String(key)
    if (text === '__proto__') return "['__proto__']"
    if (isBareIdentifier(text)) return text
    return `'${escapeStr(text)}'`
}

const ORDERED_FIELDS = [
    'id',
    'name',
    'type',
    'typeDetails',
    'genetics',
    'floweringType',
    'thc',
    'cbd',
    'cbg',
    'thcv',
    'thcRange',
    'cbdRange',
    'floweringTime',
    'floweringTimeRange',
    'description',
    'agronomic',
    'aromas',
    'dominantTerpenes',
    'lineage',
]

const formatPrimitive = (value) => {
    if (value === null) return 'null'
    if (typeof value === 'string') return `'${escapeStr(value)}'`
    if (typeof value === 'number' || typeof value === 'boolean') return String(value)
    return undefined
}

const formatValue = (value, indent) => {
    const primitive = formatPrimitive(value)
    if (primitive !== undefined) return primitive
    if (Array.isArray(value)) return formatArray(value, indent)
    if (typeof value === 'object') return formatObject(value, indent)
    return 'undefined'
}

const isScalarItem = (item) =>
    typeof item === 'string' || typeof item === 'number' || typeof item === 'boolean'

const isInlineItem = (item) => item === null || item === undefined || isScalarItem(item)

const formatArrayLines = (value, indent) => {
    const inner = ' '.repeat(indent + 4)
    const lines = ['[']
    for (const item of value) lines.push(`${inner}${formatValue(item, indent + 4)},`)
    lines.push(`${' '.repeat(indent)}]`)
    return lines.join('\n')
}

const inlineArrayParts = (value, indent) => {
    const parts = []
    for (let index = 0; index < value.length; index += 1) {
        const item = index in value ? value[index] : undefined
        if (!isInlineItem(item)) return undefined
        parts.push(formatValue(item, indent))
    }
    return parts
}

const formatArray = (value, indent) => {
    const parts = inlineArrayParts(value, indent)
    const inline = parts ? parts.join(', ') : undefined
    if (inline !== undefined && inline.length < 80) return `[${inline}]`
    return formatArrayLines(value, indent)
}

const typeFieldLiteral = (value) => {
    if (value === null) return 'null'
    if (typeof value !== 'string' || !Object.hasOwn(TYPE_ENUM, value)) return undefined
    return TYPE_ENUM[value]
}

const fieldLiteral = (key, value) => {
    if (key === 'type') return typeFieldLiteral(value)
    return formatValue(value, 8)
}

const pushField = (lines, written, key, value) => {
    if (value === undefined || written.has(key)) return
    const literal = fieldLiteral(key, value)
    if (literal === undefined) return
    const emittedKey = key === 'type' ? 'type' : emitKey(key)
    lines.push(`        ${emittedKey}: ${literal},`)
    written.add(key)
}

/**
 * Format a strain object as a createStrainObject({...}) call.
 * Missing stays omitted. Explicit null, 0 and false stay. Unknown type
 * strings stay omitted. Nested keys are escaped and never executed.
 */
export const formatStrain = (strain) => {
    const lines = ['    createStrainObject({']
    const written = new Set()
    for (const key of ORDERED_FIELDS) pushField(lines, written, key, strain[key])
    for (const key of Object.keys(strain)) pushField(lines, written, key, strain[key])
    lines.push('    }),')
    return lines.join('\n')
}

const definedEntries = (obj) => Object.entries(obj).filter(([, value]) => value !== undefined)

const isSimpleValue = (value) =>
    typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean'

const keyedEntries = (entries) => entries.map(([key, value]) => [emitKey(key), value])

const formatObjectInline = (entries, indent) => {
    const parts = entries.map(([key, value]) => `${key}: ${formatValue(value, indent)}`)
    return `{ ${parts.join(', ')} }`
}

const formatObjectLines = (entries, indent) => {
    const pad = ' '.repeat(indent)
    const innerPad = ' '.repeat(indent + 4)
    const lines = ['{']
    for (const [key, value] of entries) {
        lines.push(`${innerPad}${key}: ${formatValue(value, indent + 4)},`)
    }
    lines.push(`${pad}}`)
    return lines.join('\n')
}

const formatObject = (obj, indent) => {
    const entries = keyedEntries(definedEntries(obj))
    const allSimple = entries.every(([, value]) => isSimpleValue(value))
    if (allSimple && entries.length > 0 && entries.length <= 3) {
        return formatObjectInline(entries, indent)
    }
    return formatObjectLines(entries, indent)
}

const bucketOf = (name) => {
    const first = name.charAt(0).toLowerCase()
    if (/[0-9]/.test(first)) return 'numeric'
    if (/[a-z]/.test(first)) return first
    return 'numeric'
}

const pointerToken = (segment) => String(segment).replaceAll('~', '~0').replaceAll('/', '~1')

const collectNullPointers = (value, segments, out) => {
    if (value === null) {
        out.push(segments)
        return
    }
    if (Array.isArray(value)) {
        value.forEach((item, index) => collectNullPointers(item, segments.concat({ index }), out))
        return
    }
    if (typeof value === 'object') {
        for (const key of Object.keys(value)) {
            collectNullPointers(value[key], segments.concat({ key }), out)
        }
    }
}

const nestedNodeCount = (value) => {
    if (Array.isArray(value)) return value.reduce((sum, item) => sum + countValueNodes(item), 0)
    if (value !== null && typeof value === 'object') {
        return Object.keys(value).reduce((sum, key) => sum + countValueNodes(value[key]), 0)
    }
    return 0
}

/** Every JSON value, including containers and null. The root array is included. */
export const countValueNodes = (value) => 1 + nestedNodeCount(value)

/**
 * dataProvenance.sourceUrl is `string | null`. That null is typed only when
 * each index is an array index. A numeric object key is not an array index.
 * Every other JSON null still blocks the module write.
 */
const formatPointer = (segments) =>
    `/${segments
        .map((segment) => pointerToken(segment.index !== undefined ? segment.index : segment.key))
        .join('/')}`

const isTypedSourceUrlNull = (segments) =>
    segments.length === 4 &&
    segments[0].index !== undefined &&
    segments[1].key === 'dataProvenance' &&
    segments[2].index !== undefined &&
    segments[3].key === 'sourceUrl'

const strainId = (strain) => (typeof strain?.id === 'string' ? strain.id : '<missing-id>')

const collectFindings = (strains, index, unexpected, typed) => {
    const pointers = []
    collectNullPointers(strains[index], [{ index }], pointers)
    const id = strainId(strains[index])
    for (const segments of pointers) {
        const finding = { pointer: formatPointer(segments), id }
        if (isTypedSourceUrlNull(segments)) typed.push(finding)
        else unexpected.push(finding)
    }
}

/** Pointers are RFC 6901 paths into the strains array. The id stays a separate field. */
export const assessCatalog = (strains) => {
    const findings = []
    const typedNulls = []
    for (let index = 0; index < strains.length; index += 1) {
        collectFindings(strains, index, findings, typedNulls)
    }
    return {
        admitted: findings.length === 0,
        nullCount: findings.length,
        typedNullCount: typedNulls.length,
        pointers: findings.map((finding) => finding.pointer),
        typedPointers: typedNulls.map((finding) => finding.pointer),
        findings,
        typedNulls,
    }
}

/** `--catalog-dir` selects a fixture. The default stays the checked-in catalog. */
export const resolveCatalogDir = (argv, fallback) => {
    const index = argv.indexOf('--catalog-dir')
    if (index === -1) return fallback
    const dir = argv[index + 1]
    if (dir === undefined || dir.startsWith('--')) {
        throw new Error('[generate] --catalog-dir needs a directory')
    }
    return path.resolve(dir)
}

