    e: 'strainsE',
    f: 'strainsF',
    g: 'strainsG',
    h: 'strainsH',
    i: 'strainsI',
    j: 'strainsJ',
    k: 'strainsK',
    l: 'strainsL',
    m: 'strainsM',
    n: 'strainsN',
