const compareBuckets = (left, right) => {
    if (left === 'numeric') return -1
    if (right === 'numeric') return 1
    return left.localeCompare(right)
}

const groupStrains = (strains) => {
    const buckets = new Map()
    for (const strain of strains) {
        const bucket = bucketOf(strain.name)
        const list = buckets.get(bucket)
        if (list) list.push(strain)
        else buckets.set(bucket, [strain])
    }
    for (const list of buckets.values()) list.sort((a, b) => a.name.localeCompare(b.name))
    return buckets
}

const knownBucket = (key) => {
    if (EXPORT_NAMES[key]) return true
    console.warn(`[generate] Unknown bucket: ${key}`)
    return false
}

const renderBucket = (key, list) => {
    const exportName = EXPORT_NAMES[key]
    const content = [
        HEADER,
        '',
        `export const ${exportName}: Strain[] = [`,
        list.map(formatStrain).join('\n'),
        ']',
        '',
    ].join('\n')
    return { fileName: `${key}.ts`, content, count: list.length }
}

/** In-memory modules. Does not touch the catalog on disk. */
export const buildStrainFiles = (strains) => {
    const buckets = groupStrains(strains)
    const keys = [...buckets.keys()].sort(compareBuckets).filter(knownBucket)
    const files = keys.map((key) => renderBucket(key, buckets.get(key)))
    files.push({ fileName: 'index.ts', content: generateIndex(keys), count: 0 })
    return files
}

const reportQuarantine = (assessment) => {
    console.error(
        `[generate] Quarantine: ${assessment.nullCount} explicit JSON null values are not typed on Strain.`,
    )
    for (const finding of assessment.findings.slice(0, 3)) {
        console.error(`[generate]   ${finding.pointer} id=${finding.id}`)
    }
    console.error('[generate] Catalog files were not modified.')
}

const catalogFileName = (name) => {
    if (typeof name !== 'string' || path.basename(name) !== name || name === '' || name === '.' || name === '..') {
        throw new Error('[generate] Unsafe catalog file name')
    }
    return name
}

const openNoFollow = (filePath) =>
    fs.open(filePath, fsConstants.O_RDONLY | fsConstants.O_NOFOLLOW)

const inspectNoFollow = async (filePath) => {
    let handle
    try {
        handle = await openNoFollow(filePath)
    } catch (error) {
        if (error.code === 'ELOOP') return { isDirectory: false, isFile: false, mode: null }
        throw error
    }
    try {
        const stat = await handle.stat()
        return {
            isDirectory: stat.isDirectory(),
            isFile: stat.isFile(),
            mode: stat.isFile() ? stat.mode & 0o777 : null,
        }
    } finally {
        await handle.close()
    }
}

const chmodNoFollow = async (filePath, mode) => {
    const handle = await openNoFollow(filePath)
    try {
        await handle.chmod(mode & 0o777)
    } finally {
        await handle.close()
    }
}

const fsOps = {
    rename: (from, to) => fs.rename(from, to),
    rm: (target, options) => fs.rm(target, options),
    writeFile: (filePath, content, options) => fs.writeFile(filePath, content, options),
    mkdtemp: (prefix) => fs.mkdtemp(prefix),
    chmodNoFollow,
    inspectNoFollow,
}

/**
 * Stage every module in a private directory, then publish them together.
 * The previous file is moved aside and its mode is applied to the staged
 * inode before that inode is published. A later failure restores files
 * already moved. If a restore itself fails, the staging directory stays
 * so the backup can be recovered. The temp directory comes from mkdtemp,
 * and each staged file is opened with wx.
 */
export const commitFiles = async (dir, files, ops = {}) => {
    const io = { ...fsOps, ...ops }
    const staging = await io.mkdtemp(path.join(dir, '.strain-stage-'))
    const published = []
    let keepStaging = false
    try {
        for (const file of files) {
            const name = catalogFileName(file.fileName)
            await io.writeFile(path.join(staging, name), file.content, { encoding: 'utf8', flag: 'wx' })
        }
        for (const file of files) {
            const name = catalogFileName(file.fileName)
            const target = path.join(dir, name)
            const staged = path.join(staging, name)
            const backup = path.join(staging, `${name}.previous`)
            const item = { target, backup, backedUp: false, published: false }
            published.push(item)
            try {
                await io.rename(target, backup)
                item.backedUp = true
            } catch (error) {
                if (error.code !== 'ENOENT') throw error
            }
            if (item.backedUp) {
                const moved = await io.inspectNoFollow(backup)
                if (moved.isDirectory) {
                    throw new Error(`[generate] Refusing to replace a directory: ${name}`)
                }
                if (moved.isFile) await io.chmodNoFollow(staged, moved.mode)
            }
            await io.rename(staged, target)
            item.published = true
        }
    } catch (error) {
        for (const item of published.reverse()) {
            try {
                if (item.published) await io.rm(item.target, { force: true })
                if (item.backedUp) await io.rename(item.backup, item.target)
            } catch (restoreError) {
                keepStaging = true
                const code = restoreError && restoreError.code ? restoreError.code : 'unknown'
                console.error(
                    `[generate] Rollback failed for ${path.basename(item.target)} (${code}); backup kept in ${staging}`,
                )
            }
        }
        throw error
    } finally {
        if (!keepStaging) await io.rm(staging, { recursive: true, force: true })
    }
}

const writeCatalog = async (dir, files) => {
    await commitFiles(dir, files)
    let total = 0
    for (const file of files) {
        total += file.count
        const label = file.count > 0 ? `${file.count} strains` : 'generated'
        console.log(`[generate]   ${file.fileName}: ${label}`)
    }
    return total
}

const run = async () => {
    const dir = resolveCatalogDir(process.argv, strainsDir)
    const raw = await fs.readFile(path.join(dir, 'strains.json'), 'utf8')
    const strains = JSON.parse(raw)
    console.log(`[generate] Loaded ${strains.length} strains from strains.json`)
    const assessment = assessCatalog(strains)
    if (!assessment.admitted) {
        reportQuarantine(assessment)
        process.exitCode = 1
        return
    }
    const total = await writeCatalog(dir, buildStrainFiles(strains))
    console.log(`[generate] Total written: ${total} strains`)
}

const generateIndex = (bucketKeys) => {
    const lines = [
        '// AUTO-GENERATED by scripts/generate-strain-files.mjs',
        '// Do not edit manually. Edit strains.json and run: pnpm run strains:generate',
        "import type { Strain } from '@/types'",
        '',
    ]

    // Imports
    for (const key of bucketKeys) {
        const exportName = EXPORT_NAMES[key]
        lines.push(`import { ${exportName} } from './${key}'`)
    }

    lines.push('')
    lines.push('/**')
    lines.push(' * Combined strain catalog.')
    lines.push(' * All strains are organized in alphabetical files (a.ts-z.ts, numeric.ts).')
    lines.push(' * De-duplicated by ID to ensure data integrity.')
    lines.push(' */')
    lines.push('const combinedStrains: Strain[] = [')
    for (const key of bucketKeys) {
        const exportName = EXPORT_NAMES[key]
        lines.push(`    ...${exportName},`)
    }
    lines.push(']')
    lines.push('')
    lines.push('// De-duplicate strains by ID to ensure data integrity from the source.')
    lines.push(
        'const deduplicatedMap = new Map(combinedStrains.map((strain) => [strain.id, strain]))',
    )
    lines.push('')
    lines.push('if (import.meta.env.DEV && deduplicatedMap.size < combinedStrains.length) {')
    lines.push('    const duplicateCount = combinedStrains.length - deduplicatedMap.size')
    lines.push('    const idCounts = new Map<string, number>()')
    lines.push('    for (const strain of combinedStrains) {')
    lines.push('        idCounts.set(strain.id, (idCounts.get(strain.id) ?? 0) + 1)')
    lines.push('    }')
    lines.push(
        '    const duplicateIds = [...idCounts.entries()].filter(([, count]) => count > 1).map(([id]) => id)',
    )
    lines.push('    console.debug(')
    lines.push(
        "        `[Strains] ${duplicateCount} duplicate strain(s) detected and auto-deduplicated. IDs: ${duplicateIds.join(', ')}`,",
    )
    lines.push('    )')
    lines.push('}')
    lines.push('')
    lines.push('export const allStrainsData: Strain[] = Array.from(deduplicatedMap.values())')
    lines.push('')

    return lines.join('\n')
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (invokedDirectly) {
    run().catch((err) => {
        console.error('[generate] Fatal error:', err)
        process.exit(1)
    })
}
